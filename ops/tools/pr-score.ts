/**
 * npm run ops:pr-score
 *
 * Reads .pr-eval/result.json, validates it, computes the score and writes
 * .pr-eval/comment.md. Exit code 1 when result.json is missing or invalid.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { computeScore, validateResult, type EvalItem, type ResultJson } from './lib/pr-eval'
import { displayPath, parseCli, repoRoot } from './lib/cli'

parseCli(
  'npx tsx ops/tools/pr-score.ts',
  'Reads .pr-eval/result.json, validates it, computes the score and writes .pr-eval/comment.md.',
  {}
)

const evalDir = path.join(repoRoot, '.pr-eval')
const resultPath = path.join(evalDir, 'result.json')
const commentPath = path.join(evalDir, 'comment.md')

// ---------------------------------------------------------------------------
// Read and validate
// ---------------------------------------------------------------------------

if (!existsSync(resultPath)) {
  console.error(`pr-score: ${displayPath(resultPath)} not found — the agent must write it first`)
  process.exit(1)
}

let data: unknown
try {
  data = JSON.parse(readFileSync(resultPath, 'utf-8'))
} catch (e) {
  console.error(`pr-score: ${displayPath(resultPath)} is not valid JSON: ${(e as Error).message}`)
  process.exit(1)
}

const errors = validateResult(data)
if (errors.length > 0) {
  console.error(`pr-score: result.json is invalid:`)
  for (const e of errors) console.error(`  - ${e}`)
  process.exit(1)
}

const result = data as ResultJson
const items = result.items as EvalItem[]
const findings = result.findings ?? []

// ---------------------------------------------------------------------------
// Score
// ---------------------------------------------------------------------------

const score = computeScore(items)
const scoreText = `${score.passed}/${score.passed + score.failed}`

// ---------------------------------------------------------------------------
// Build comment.md
// ---------------------------------------------------------------------------

const lines: string[] = []

lines.push('<!-- pr-evaluator -->')
lines.push('')

const nvNote = score.notVerifiable > 0
  ? ` — ${score.notVerifiable} NOT VERIFIABLE`
  : ''

lines.push(`## PR Evaluation: ${scoreText}${nvNote} — model: ${result.model}`)
lines.push('')

// Verdict table
lines.push('| id | criterion | source | verdict | evidence |')
lines.push('|---|---|---|---|---|')

const allItems = [...items].sort((a, b) => {
  const order = { 'FAIL': 0, 'NOT VERIFIABLE': 1, 'PASS': 2 }
  return (order[a.verdict] ?? 3) - (order[b.verdict] ?? 3)
})

for (const item of allItems) {
  const evidence = item.evidence.replace(/\n/g, ' ').replace(/\|/g, '&#124;')
  const verdictBadge = item.verdict === 'FAIL'
    ? '**FAIL**'
    : item.verdict === 'NOT VERIFIABLE'
      ? '*NOT VERIFIABLE*'
      : 'PASS'
  lines.push(`| ${item.id} | ${item.criterion.replace(/\|/g, '&#124;')} | ${item.source} | ${verdictBadge} | ${evidence} |`)
}

lines.push('')

// NOT VERIFIABLE list (reasons)
const nvItems = items.filter(i => i.verdict === 'NOT VERIFIABLE')
if (nvItems.length > 0) {
  lines.push('### NOT VERIFIABLE')
  lines.push('')
  for (const item of nvItems) {
    lines.push(`- **${item.id}** (${item.source}): ${item.criterion}`)
    if (item.evidence) lines.push(`  - ${item.evidence}`)
  }
  lines.push('')
}

// Findings
if (findings.length > 0) {
  lines.push('### Findings')
  lines.push('')
  for (const finding of findings) {
    lines.push(`- ${finding}`)
  }
  lines.push('')
}

// Footer
lines.push('---')
lines.push(
  '*This evaluation is advisory and was generated by an AI agent. ' +
  'It is not an approval and does not replace human review. ' +
  'A passing score does not mean the change is correct or safe to merge.*'
)
lines.push('')

const commentMd = lines.join('\n')
writeFileSync(commentPath, commentMd, 'utf-8')

// ---------------------------------------------------------------------------
// Summary to stdout
// ---------------------------------------------------------------------------

console.log(`pr-score: ${scoreText} (${score.passed} PASS, ${score.failed} FAIL, ${score.notVerifiable} NOT VERIFIABLE)`)
if (findings.length > 0) {
  console.log(`pr-score: ${findings.length} finding(s)`)
}
console.log(`pr-score: wrote ${displayPath(commentPath)}`)
